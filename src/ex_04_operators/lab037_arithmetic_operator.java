package ex_04_operators;

public class lab037_arithmetic_operator {
    public static void main(String[] args) {
        int a=20;
        float b=10.5f;
        System.out.println(a+b);
        System.out.println(a-b);
        System.out.println(a*b);
        System.out.println(a/b);


        int c=20;
        int d=3;
        System.out.println(c+d);
        System.out.println(c-d);
        System.out.println(c*d);
        System.out.println(c/d);


        //if int c=20;float d=3f;sout(a/b)=6.66666665

        
    }
}
