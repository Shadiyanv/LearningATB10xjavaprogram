package ex_16_Arrays;

public class lab153_1D_array {
    public static void main(String[] args) {
        int[] a=new int[5];
        a[0]=-90;
        a[1]=-91;
        a[2]=89;
        a[3]=41;
        a[4]=39;

        for(int i=0;i<a.length;i++){
            System.out.println(a[i]);
        }
    }
}
