package ex_09_switch;

public class lab098_IQ {
    public static void main(String[] args) {
        char code='C';
        switch(code){
            case 'A':
                System.out.println("66");
                break;
            case 'B':
                System.out.println("65");
                break;
            default:
                System.out.println("hello");
                break;


        }
    }
}
